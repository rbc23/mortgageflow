--------------------------------------------------------------------------------------------
-- 1. APP_USERS
--------------------------------------------------------------------------------------------

CREATE TABLE app_users(user_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                       username      VARCHAR2(50) NOT NULL,
                       email         VARCHAR2(100) NOT NULL,
                       full_name     VARCHAR2(100) NOT NULL,
                       password_hash VARCHAR2(255) NOT NULL,
                       role          VARCHAR2(30) DEFAULT 'APPLICANT' NOT NULL,
                       active_yn     CHAR(1) DEFAULT 'Y' NOT NULL,
                       created_at    TIMESTAMP DEFAULT Systimestamp NOT NULL,
                       updated_at    TIMESTAMP DEFAULT Systimestamp NOT NULL,
                       CONSTRAINT pk_app_users PRIMARY KEY (user_id),
                       CONSTRAINT uq_app_users_username UNIQUE (username),
                       CONSTRAINT uq_app_users_email UNIQUE (email),
                       CONSTRAINT ck_app_users_role CHECK ( role IN ( 'APPLICANT', 'LOAN_OFFICER', 'ADMIN' ) ),
                       CONSTRAINT ck_app_users_active CHECK (active_yn IN ('Y', 'N')) );

--------------------------------------------------------------------------------------------
-- 2. LOAN_PRODUCTS
--------------------------------------------------------------------------------------------
/*
Examples would be:
- 15-Year Fixed Mortgage
- 20-Year Fixed Mortgage
- 30-Year Fixed Mortgage

*/

CREATE TABLE loan_products(loan_product_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                           product_name      VARCHAR2(100) NOT NULL,
                           description       VARCHAR2(2000),
                           term_years        NUMBER(3) NOT NULL,
                           min_interest_rate NUMBER(5,4) NOT NULL,
                           max_interest_rate NUMBER(5,4) NOT NULL,
                           active_yn         CHAR(1) DEFAULT 'Y' NOT NULL,
                           created_at        TIMESTAMP DEFAULT Systimestamp NOT NULL,
                           updated_at        TIMESTAMP DEFAULT Systimestamp NOT NULL,
                           CONSTRAINT pk_loan_products PRIMARY KEY (loan_product_id),
                           CONSTRAINT uq_loan_products_name UNIQUE (product_name),
                           CONSTRAINT ck_loan_products_term CHECK (term_years > 0),
                           CONSTRAINT ck_loan_products_min_rate CHECK (min_interest_rate >= 0),
                           CONSTRAINT ck_loan_products_max_rate CHECK (max_interest_rate >= min_interest_rate),
                           CONSTRAINT ck_loan_products_active CHECK (active_yn IN ('Y', 'N')) );


--------------------------------------------------------------------------------------------
-- 3. INTEREST_RATES
--------------------------------------------------------------------------------------------
-- This gives you rate history instead of overwriting a rate every time it changes.

CREATE TABLE interest_rates(rate_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                            loan_product_id NUMBER NOT NULL,
                            interest_rate   NUMBER(5,4) NOT NULL,
                            effective_from  DATE NOT NULL,
                            effective_to    DATE,
                            active_yn       CHAR(1) DEFAULT 'Y' NOT NULL,
                            created_at      TIMESTAMP DEFAULT Systimestamp NOT NULL,
                            updated_at      TIMESTAMP DEFAULT Systimestamp NOT NULL,
                            CONSTRAINT pk_interest_rates PRIMARY KEY (rate_id),
                            CONSTRAINT fk_rates_product FOREIGN KEY (loan_product_id) REFERENCES loan_products (loan_product_id),
                            CONSTRAINT ck_interest_rates_rate CHECK (interest_rate >= 0),
                            CONSTRAINT ck_interest_rates_dates CHECK ( effective_to IS NULL OR effective_to >= effective_from ),
                            CONSTRAINT ck_interest_rates_active CHECK (active_yn IN ('Y', 'N')),
                            CONSTRAINT uq_interest_rates UNIQUE ( loan_product_id, effective_from ) );

CREATE INDEX ix_interest_rates_product ON interest_rates (loan_product_id);

--------------------------------------------------------------------------------------------
-- 4. MORTGAGE_APPLICATIONS
--------------------------------------------------------------------------------------------
-- This is the main table of the entire system.




CREATE TABLE mortgage_applications(application_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                   application_number VARCHAR2(30) NOT NULL,
                                   applicant_user_id  NUMBER NOT NULL,
                                   loan_product_id    NUMBER NOT NULL,
                                   annual_income      NUMBER(15,2) NOT NULL,
                                   monthly_debt       NUMBER(15,2) DEFAULT 0 NOT NULL,
                                   property_value     NUMBER(15,2) NOT NULL,
                                   down_payment       NUMBER(15,2) DEFAULT 0 NOT NULL,
                                   loan_amount        NUMBER(15,2) NOT NULL,
                                   interest_rate      NUMBER(5,4) NOT NULL,
                                   loan_term_years    NUMBER(3) NOT NULL, monthly_payment    NUMBER(15,2),
                                   ltv                NUMBER(5,2), dti                NUMBER(5,2), risk_level         VARCHAR2(20),
                                   status             VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
                                   submitted_at       TIMESTAMP, decided_at         TIMESTAMP, decided_by         NUMBER,
                                   created_at         TIMESTAMP DEFAULT Systimestamp NOT NULL,
                                   updated_at         TIMESTAMP DEFAULT Systimestamp NOT NULL,
                                   CONSTRAINT pk_mortgage_applications PRIMARY KEY (application_id),
                                   CONSTRAINT uq_mortgage_application_number UNIQUE (application_number),
                                   CONSTRAINT fk_mortgage_applicant FOREIGN KEY (applicant_user_id) REFERENCES app_users (user_id),
                                   CONSTRAINT fk_mortgage_product FOREIGN KEY (loan_product_id) REFERENCES loan_products (loan_product_id),
                                   CONSTRAINT fk_mortgage_decided_by FOREIGN KEY (decided_by) REFERENCES app_users (user_id),
                                   CONSTRAINT ck_mortgage_income CHECK (annual_income > 0),
                                   CONSTRAINT ck_mortgage_monthly_debt CHECK (monthly_debt >= 0),
                                   CONSTRAINT ck_mortgage_property_value CHECK (property_value > 0),
                                   CONSTRAINT ck_mortgage_down_payment CHECK ( down_payment >= 0 AND down_payment <= property_value ),
                                   CONSTRAINT ck_mortgage_loan_amount CHECK ( loan_amount > 0 AND loan_amount <= property_value ),
                                   CONSTRAINT ck_mortgage_interest_rate CHECK (interest_rate >= 0),
                                   CONSTRAINT ck_mortgage_term CHECK (loan_term_years > 0),
                                   CONSTRAINT ck_mortgage_payment CHECK ( monthly_payment IS NULL OR monthly_payment >= 0 ),
                                   CONSTRAINT ck_mortgage_ltv CHECK ( ltv IS NULL OR ltv >= 0 ),
                                   CONSTRAINT ck_mortgage_dti CHECK ( dti IS NULL OR dti >= 0 ),
                                   CONSTRAINT ck_mortgage_risk CHECK ( risk_level IS NULL OR risk_level IN ( 'LOW', 'MEDIUM', 'HIGH' ) ),
                                   CONSTRAINT ck_mortgage_status CHECK ( status IN ( 'DRAFT', 'SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED' ) ) );

CREATE INDEX ix_mortgage_applicant ON mortgage_applications (applicant_user_id);

CREATE INDEX ix_mortgage_product ON mortgage_applications (loan_product_id);

CREATE INDEX ix_mortgage_status ON mortgage_applications (status);

CREATE INDEX ix_mortgage_risk ON mortgage_applications (risk_level);

CREATE INDEX ix_mortgage_decided_by ON mortgage_applications (decided_by);

	

--------------------------------------------------------------------------------------------
-- 5. APPLICATION_STATUS_HISTORY
--------------------------------------------------------------------------------------------
/*
Every time the application status changes, insert a record here.
Example:
DRAFT → SUBMITTED
SUBMITTED → UNDER_REVIEW
UNDER_REVIEW → APPROVED
*/


CREATE TABLE application_status_history(history_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                        application_id NUMBER NOT NULL,
                                        old_status     VARCHAR2(20),
                                        new_status     VARCHAR2(20) NOT NULL,
                                        changed_by     NUMBER NOT NULL,
                                        changed_at     TIMESTAMP DEFAULT Systimestamp NOT NULL,
                                        comments       VARCHAR2(4000),
                                        CONSTRAINT pk_application_status_history PRIMARY KEY (history_id),
                                        CONSTRAINT fk_status_history_application FOREIGN KEY (application_id) REFERENCES mortgage_applications (application_id),
                                        CONSTRAINT fk_status_history_user FOREIGN KEY (changed_by) REFERENCES app_users (user_id),
                                        CONSTRAINT ck_status_history_old CHECK ( old_status IS NULL OR old_status IN ( 'DRAFT', 'SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED' ) ),
                                        CONSTRAINT ck_status_history_new CHECK ( new_status IN ( 'DRAFT', 'SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED' ) ) );

CREATE INDEX ix_status_history_application ON application_status_history (application_id);

CREATE INDEX ix_status_history_user ON application_status_history (changed_by);

CREATE INDEX ix_status_history_date ON application_status_history (changed_at);



--------------------------------------------------------------------------------------------
-- 6. AUDIT_LOG
--------------------------------------------------------------------------------------------
-- It records significant actions throughout the application.


CREATE TABLE audit_log(audit_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                       application_id NUMBER,
                       user_id        NUMBER,
                       action_type    VARCHAR2(50) NOT NULL,
                       description    VARCHAR2(4000),
                       created_at     TIMESTAMP DEFAULT Systimestamp NOT NULL,
                       CONSTRAINT pk_audit_log PRIMARY KEY (audit_id),
                       CONSTRAINT fk_audit_application FOREIGN KEY (application_id) REFERENCES mortgage_applications (application_id),
                       CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES app_users (user_id) );

CREATE INDEX ix_audit_application ON audit_log (application_id);

CREATE INDEX ix_audit_user ON audit_log (user_id);

CREATE INDEX ix_audit_created_at ON audit_log (created_at);

CREATE INDEX ix_audit_action ON audit_log (action_type);

--------------------------------------------------------------------------------------------
-- 7. APP_ERROR_LOG
--------------------------------------------------------------------------------------------
-- This is the centralized technical error table.


CREATE TABLE app_error_log(error_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                           application_id  NUMBER,
                           user_id         NUMBER,
                           page_id         NUMBER,
                           error_code      VARCHAR2(50),
                           error_message   VARCHAR2(4000),
                           error_stack     CLOB,
                           error_backtrace CLOB,
                           created_at      TIMESTAMP DEFAULT Systimestamp NOT NULL,
                           CONSTRAINT pk_app_error_log PRIMARY KEY (error_id),
                           CONSTRAINT fk_error_application FOREIGN KEY (application_id) REFERENCES mortgage_applications (application_id),
                           CONSTRAINT fk_error_user FOREIGN KEY (user_id) REFERENCES app_users (user_id) );

CREATE INDEX ix_error_application ON app_error_log (application_id);

CREATE INDEX ix_error_user ON app_error_log (user_id);

CREATE INDEX ix_error_created_at ON app_error_log (created_at);


