-- 8. Automatically update UPDATED_AT
--------------------------------------------------------------------------------------------
-- These triggers update the timestamp when a row changes.


CREATE OR replace TRIGGER trg_app_users_updated
  BEFORE UPDATE ON app_users
  FOR EACH ROW
BEGIN
    :new.updated_at := systimestamp;
END;

/
CREATE OR replace TRIGGER trg_loan_products_updated
  BEFORE UPDATE ON loan_products
  FOR EACH ROW
BEGIN
    :new.updated_at := systimestamp;
END;

/
CREATE OR replace TRIGGER trg_interest_rates_updated
  BEFORE UPDATE ON interest_rates
  FOR EACH ROW
BEGIN
    :new.updated_at := systimestamp;
END;

/
CREATE OR replace TRIGGER trg_mortgage_apps_updated
  BEFORE UPDATE ON mortgage_applications
  FOR EACH ROW
BEGIN
    :new.updated_at := systimestamp;
END;

